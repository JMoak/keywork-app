const freeOfTheGround: ReadonlySet<PoseName> = new Set(["celebrate", "greet", "raise"]);
const contactRow = groundLine - 1;

function everyFrame(): { pose: PoseName; frame: number; cell: Uint8Array }[] {
  return poseNames.flatMap((pose) =>
    Array.from({ length: skin.rows[pose].frames }, (_, frame) => ({
      pose,
      frame,
      cell: frameOf(skin, pose, frame),
    })),
  );
}

function pixel(cell: Uint8Array, x: number, y: number): number {
  if (x < 0 || y < 0 || x >= cellWidth || y >= cellHeight) return -1;
  return cell[y * cellWidth + x] ?? 0;
}

function lowestOpaqueRow(cell: Uint8Array): number {
  let lowest = -1;
  cell.forEach((index, at) => {
    if (index !== 0) lowest = Math.max(lowest, Math.floor(at / cellWidth));
  });
  return lowest;
}

function unoutlinedFills(cell: Uint8Array): string[] {
  const faults: string[] = [];
  for (let y = 0; y < cellHeight; y += 1) {
    for (let x = 0; x < cellWidth; x += 1) {
      const index = pixel(cell, x, y);
      if (index === 0 || index === 9) continue;
      const neighbours = [
        pixel(cell, x - 1, y),
        pixel(cell, x + 1, y),
        pixel(cell, x, y - 1),
        pixel(cell, x, y + 1),
      ];
      if (neighbours.some((neighbour) => neighbour <= 0)) faults.push(`${x},${y}`);
    }
  }
  return faults;
}

function differingPixels(a: Uint8Array, b: Uint8Array): { x: number; y: number }[] {
  const differing: { x: number; y: number }[] = [];
  a.forEach((index, at) => {
    if (index !== b[at]) differing.push({ x: at % cellWidth, y: Math.floor(at / cellWidth) });
  });
  return differing;
}

function pixelsOutsideTheCell(placement: Placement): string[] {
  const { sprite, x, y } = resolvedSprite(placement);
  const outlined = placement.outline || placement.layer === "skin";
  const clipped: string[] = [];
  for (let j = 0; j < sprite.height; j += 1) {
    for (let i = 0; i < sprite.width; i += 1) {
      const index = sprite.pixels[j * sprite.width + i] ?? 0;
      if (index === 0) continue;
      const margin = outlined && index !== 9 ? 1 : 0;
      const left = x + i - margin;
      const top = y + j - margin;
      const right = x + i + margin;
      const bottom = y + j + margin;
      if (left < 0 || top < 0 || right >= cellWidth || bottom >= cellHeight) {
        clipped.push(`${x + i},${y + j}`);
      }
    }
  }
  return clipped;
}

function bandOf(named: typeof parts.torso) {
  if (named.band === undefined) throw new Error(`${named.name} has no band`);
  return named.band;
}

describe("kidSkin manifest", () => {
  it("is deterministic: two generations are byte-identical", () => {
    const again = kidSkin();
    expect(again.atlas.indices).toEqual(skin.atlas.indices);
    expect(again.rows).toEqual(skin.rows);
    expect(again).toEqual(skin);
  });

  it("matches the Skin shape with the palette roles and ground line of the art direction", () => {
    expect(skin.id).toBe("kid");
    expect(skin.cell).toEqual({ width: 48, height: 52 });
    expect(skin.palette).toEqual({
      identity: [1, 2, 3, 4],
      ground: [5, 6, 7, 8],
      outline: 9,
      accent: [10, 11, 12],
    });
    expect(skin.groundLine).toBe(51);
    expect(skin.gaze).toEqual({ row: poseNames.indexOf("look"), directions: 8 });
  });

  it("declares every pose with the frame counts, beats, loops and fallbacks of the art direction", () => {
    expect(skin.rows).toEqual(artDirection);
  });

  it("lays rows times frames out inside the atlas grid", () => {
    const columns = Math.max(...poseNames.map((pose) => skin.rows[pose].frames));
    expect(columns).toBe(8);
    expect(skin.atlas.width).toBe(skin.cell.width * columns);
    expect(skin.atlas.height).toBe(skin.cell.height * poseNames.length);
    expect(skin.atlas.indices).toBeInstanceOf(Uint8Array);
    expect(skin.atlas.indices.length).toBe(skin.atlas.width * skin.atlas.height);
    for (const pose of poseNames) expect(skin.rows[pose].frames).toBeLessThanOrEqual(columns);
  });

  it("leaves the cells past a row's last frame transparent", () => {
    for (const pose of poseNames) {
      const row = poseNames.indexOf(pose);
      for (let column = skin.rows[pose].frames; column < 8; column += 1) {
        for (let y = 0; y < cellHeight; y += 1) {
          const start = (row * cellHeight + y) * skin.atlas.width + column * cellWidth;
          const line = skin.atlas.indices.subarray(start, start + cellWidth);
          expect(line.every((index) => index === 0)).toBe(true);
        }
      }
    }
  });

  it("holds every frame a positive time and the last frame longest, as the pose beat", () => {
    for (const pose of poseNames) {
      const { ms, frames } = skin.rows[pose];
      expect(ms).toHaveLength(frames);
      for (const hold of ms) expect(hold).toBeGreaterThan(0);
      const last = ms[ms.length - 1] ?? 0;
      expect(last).toBe(Math.max(...ms));
      if (pose !== "look") expect(last).toBeGreaterThanOrEqual(1.6 * (ms[ms.length - 2] ?? 0));
    }
  });

  it("gives every one-shot a fallback that settles on a loop", () => {
    for (const pose of poseNames) {
      const row = skin.rows[pose];
      if (row.loop) continue;
      expect(row.fallback).toBeDefined();
      const fallback = skin.rows[row.fallback ?? "idle"];
      expect(fallback.loop || skin.rows[fallback.fallback ?? "idle"].loop).toBe(true);
    }
  });

  it("builds the whole atlas in under 50 ms", () => {
    const runs = Array.from({ length: 3 }, () => {
      const started = performance.now();
      kidSkin();
      return performance.now() - started;
    });
    expect(Math.min(...runs)).toBeLessThan(50);
  });
});

describe("every frame", () => {
  it("uses only the thirteen creature indices, with binary alpha", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      const used = new Set(cell);
      for (const index of used) expect(index, `${pose} ${frame}`).toBeLessThan(13);
      expect(used.size, `${pose} ${frame}`).toBeGreaterThan(1);
    }
  });

  it("has a dark outline around every opaque region: only index 9 touches transparency or the cell edge", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      expect(unoutlinedFills(cell), `${pose} ${frame}`).toEqual([]);
    }
  });

  it("stands on the fixed ground line in every row except celebrate, greet and raise", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      if (freeOfTheGround.has(pose)) continue;
      expect(lowestOpaqueRow(cell), `${pose} ${frame}`).toBe(contactRow);
    }
  });

  it("leaves the ground only on the declared airborne frames", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      const airborne = (airborneFrames[pose] ?? []).includes(frame);
      if (airborne) expect(lowestOpaqueRow(cell), `${pose} ${frame}`).toBeLessThan(contactRow);
      else expect(lowestOpaqueRow(cell), `${pose} ${frame}`).toBeLessThanOrEqual(contactRow);
    }
    expect(airborneFrames.celebrate).toEqual([1, 2]);
    expect(airborneFrames.greet).toEqual([1, 2]);
  });

  it("keeps the row under the ground line clear", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      const margin = cell.subarray(groundLine * cellWidth);
      expect(
        margin.every((index) => index === 0),
        `${pose} ${frame}`,
      ).toBe(true);
    }
  });

  it("never places a part above row 0 or beyond the cell, outline included", () => {
    for (const pose of poseNames) {
      for (const placements of clipBuilders[pose]().placements) {
        for (const placement of placements) {
          const clipped = pixelsOutsideTheCell(placement);
          expect(clipped, `${pose} ${placement.part.name}`).toEqual([]);
        }
      }
    }
  });

  it("keeps the crown clear for the glyph in the standing rows", () => {
    for (const { pose, frame, cell } of everyFrame()) {
      if (pose === "hammer" || pose === "stretch" || pose === "wave" || pose === "ring") continue;
      for (let x = 18; x <= 30; x += 1)
        expect(pixel(cell, x, 0), `${pose} ${frame} at ${x}`).toBe(0);
    }
  });
});

describe("the poses", () => {
  it("idle breathes and blinks with visible micro-variation, returning to the model pose", () => {
    const frames = Array.from({ length: 6 }, (_, frame) => frameOf(skin, "idle", frame));
    for (let a = 0; a < 5; a += 1) {
      for (let b = a + 1; b < 5; b += 1) expect(frames[a]).not.toEqual(frames[b]);
    }
    expect(frames[5]).toEqual(frames[0]);
    expect(lowestOpaqueRow(frames[1] ?? new Uint8Array())).toBe(contactRow);
  });

  it("mirrors walk-left into walk-right", () => {
    for (let frame = 0; frame < 8; frame += 1) {
      expect(frameOf(skin, "walk-right", frame)).toEqual(
        mirrorCell(frameOf(skin, "walk-left", frame)),
      );
    }
  });

  it("walks with the feet on the ground and the body bobbing on the pass frames", () => {
    const contact = frameOf(skin, "walk-left", 0);
    const pass = frameOf(skin, "walk-left", 2);
    expect(lowestOpaqueRow(contact)).toBe(contactRow);
    expect(lowestOpaqueRow(pass)).toBe(contactRow);
    const hornTip = (cell: Uint8Array) => cell.findIndex((index) => index !== 0);
    expect(Math.floor(hornTip(pass) / cellWidth)).toBe(
      Math.floor(hornTip(contact) / cellWidth) - 1,
    );
  });

  it("gives the look row eight distinct directions around the model pose", () => {
    const directions = Array.from({ length: 8 }, (_, frame) => frameOf(skin, "look", frame));
    const model = frameOf(skin, "idle", 0);
    for (const direction of directions) expect(direction).not.toEqual(model);
    expect(new Set(directions.map((cell) => cellToAscii(cell))).size).toBe(8);
  });

  it("wears the goggles up at idle and while waiting, down on tools, fogged when blocked", () => {
    const eyeRow = (cell: Uint8Array) => [pixel(cell, 19, 17), pixel(cell, 28, 17)];
    expect(eyeRow(frameOf(skin, "idle", 0))).toEqual([9, 9]);
    expect(eyeRow(frameOf(skin, "wait", 5))).toEqual([4, 4]);
    for (const tools of ["work", "hammer", "carve"] as const) {
      const lens = pixel(frameOf(skin, tools, 0), 21, 17);
      expect([5, 6, 7, 8], `${tools} lens`).toContain(lens);
    }
    const blocked = frameOf(skin, "blocked", 0);
    expect(pixel(blocked, 14, 21)).toBe(9);
    expect(pixel(blocked, 15, 21)).toBe(8);
    expect(pixel(blocked, 16, 21)).toBe(9);
  });

  it("keeps the hammer in the belt at idle, in hand at work and on the ground when blocked", () => {
    const belt = frameOf(skin, "idle", 0);
    expect(pixel(belt, 9, 41)).toBe(5);
    expect(pixel(belt, 9, 44)).toBe(7);
    const work = frameOf(skin, "work", 0);
    expect(pixel(work, 4, 36)).toBe(5);
    expect(pixel(work, 8, 36)).toBe(7);
    expect(pixel(work, 9, 41)).not.toBe(5);
    const blocked = frameOf(skin, "blocked", 0);
    expect(pixel(blocked, 45, 48)).toBe(5);
    expect(pixel(blocked, 40, 48)).toBe(7);
  });

  it("bulges the apron pocket on the flag without touching the rest of the body", () => {
    const flat = compose(kid());
    const full = compose(kid({ pocket: "full" }));
    const changed = differingPixels(flat, full);
    expect(changed.length).toBeGreaterThan(20);
    for (const { x, y } of changed) {
      expect(x).toBeGreaterThanOrEqual(19);
      expect(x).toBeLessThanOrEqual(29);
      expect(y).toBeGreaterThanOrEqual(39);
      expect(y).toBeLessThanOrEqual(45);
    }
  });

  it("squashes and stretches the torso while keeping its area within five percent", () => {
    const model = opaqueCount(parts.torso.sprite);
    const squashed = opaqueCount(deformSprite(parts.torso.sprite, bandOf(parts.torso), -1, 1));
    const stretched = opaqueCount(deformSprite(parts.torso.sprite, bandOf(parts.torso), 1, -1));
    expect(Math.abs(squashed - model) / model).toBeLessThan(0.05);
    expect(Math.abs(stretched - model) / model).toBeLessThan(0.05);
    const hornTip = (cell: Uint8Array) =>
      Math.floor(cell.findIndex((index) => index !== 0) / cellWidth);
    expect(hornTip(compose(kid({ squash: 1 })))).toBe(hornTip(compose(kid())) + 1);
    expect(hornTip(compose(kid({ squash: -1 })))).toBe(hornTip(compose(kid())) - 1);
    expect(lowestOpaqueRow(compose(kid({ squash: 1 })))).toBe(contactRow);
  });

  it("raises the hammer head above the head line at the apex of a blow", () => {
    const apex = frameOf(skin, "hammer", 1);
    const headTop = Math.floor(frameOf(skin, "idle", 0).indexOf(2) / cellWidth);
    const hammerRows = [];
    for (let y = 0; y < headTop; y += 1) {
      for (let x = 0; x < cellWidth; x += 1) if (pixel(apex, x, y) === 5) hammerRows.push(y);
    }
    expect(hammerRows.length).toBeGreaterThan(0);
  });

  it("puts the crate at the chest while carrying and on the ground once delivered", () => {
    const carrying = frameOf(skin, "carry", 0);
    expect(pixel(carrying, 24, 29)).toBe(8);
    const delivered = frameOf(skin, "deliver", 4);
    expect(pixel(delivered, 7, 41)).toBe(8);
    expect(pixel(delivered, 7, 49)).toBe(5);
    expect(lowestOpaqueRow(delivered)).toBe(contactRow);
  });

  it("rings with both hands on the rope and the bell in the needs-you index while it swings", () => {
    const swinging = frameOf(skin, "ring", 2);
    const bellPixels = swinging.filter((index) => index === 11).length;
    expect(bellPixels).toBeGreaterThan(10);
    expect(frameOf(skin, "ring", 0).includes(11)).toBe(false);
    expect(frameOf(skin, "ring", 4).includes(11)).toBe(false);
    expect([pixel(swinging, 11, 27), pixel(swinging, 11, 29)]).toEqual([1, 1]);
  });

  it("sweats from the fifth blocked frame on", () => {
    for (let frame = 0; frame < 5; frame += 1)
      expect(frameOf(skin, "blocked", frame).includes(8)).toBe(true);
    const dry = frameOf(skin, "blocked", 4);
    const damp = frameOf(skin, "blocked", 7);
    expect(
      differingPixels(dry, damp).some(({ x, y }) => pixel(damp, x, y) === 8 && y > 18 && y < 25),
    ).toBe(true);
  });
});

describe("the parts kit", () => {
  it("parses legend rows into sprites and refuses ragged rows or unknown glyphs", () => {
    const dot = part("dot", 0, 0, ["c"]);
    expect(dot.sprite).toEqual({ width: 1, height: 1, pixels: new Uint8Array([2]) });
    expect(() => part("ragged", 0, 0, ["cc", "c"])).toThrow(/wide/);
    expect(() => part("odd", 0, 0, ["cx"])).toThrow(/legend/);
  });

  it("outlines a fill with the outline index on its four sides only", () => {
    const outlined = outlineSprite(part("dot", 0, 0, ["c"]).sprite);
    expect(cellToAsciiRows(outlined.pixels, outlined.width)).toEqual([".o.", "oco", ".o."]);
  });

  it("mirrors sprites exactly and twice returns the original", () => {
    const horn = parts.horn.sprite;
    expect(mirrorSprite(mirrorSprite(horn))).toEqual(horn);
    expect(cellToAsciiRows(mirrorSprite(horn).pixels, horn.width)[0]).toBe("......o");
  });

  it("grows and shrinks a band by whole rows and columns", () => {
    const box = part("box", 0, 0, ["ccc", "ccc", "ccc"], { rows: [0, 2], cols: [0, 2] });
    const grown = deformSprite(box.sprite, bandOf(box), 2, 1);
    expect([grown.width, grown.height]).toEqual([5, 5]);
    expect(opaqueCount(grown)).toBe(25);
    const shrunk = deformSprite(box.sprite, bandOf(box), -1, -1);
    expect([shrunk.width, shrunk.height]).toEqual([1, 2]);
  });

  it("round-trips a cell through its ASCII form", () => {
    const cell = frameOf(skin, "nap", 0);
    expect(cellFromAscii(cellToAscii(cell))).toEqual(cell);
    expect(renderFrameAscii(skin, "nap", 0)).toBe(cellToAscii(cell));
    expect(() => frameOf(skin, "nap", 4)).toThrow(/4 frames/);
  });
});

function cellToAsciiRows(pixels: Uint8Array, width: number): string[] {
  const rows: string[] = [];
  for (let start = 0; start < pixels.length; start += width) {
    rows.push(
      Array.from(pixels.subarray(start, start + width), (index) =>
        ".sclhdgwpo*@!DEF".charAt(index),
      ).join(""),
    );
  }
  return rows;
}

